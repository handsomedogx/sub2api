import { beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import CyberEvidencePanel from '../CyberEvidencePanel.vue'
import CyberEvidenceSettings from '../CyberEvidenceSettings.vue'

const api = vi.hoisted(() => ({ getEvidence: vi.fn(), exportEvidence: vi.fn(), deleteEvidence: vi.fn(), getEvidenceConfig: vi.fn(), updateEvidenceConfig: vi.fn() }))
vi.mock('@/api/admin/cyberEvidence', () => api)
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key, te: () => true }) }))
const fixture = () => ({ log_id: 7, user_id: 42, request_id: 'req_synthetic', endpoint: '/v1/chat/completions', model: 'synthetic', occurred_at: '2026-10-22T00:00:00Z', status: 'saved', payload: { input: '{"messages":[{"role":"user","content":"SYNTHETIC INPUT"}]}', upstream_reason: 'SYNTHETIC UPSTREAM ERROR', source: 'upstream_error_code:cyber_policy', redaction_version: 'cyber-evidence-v1', original_bytes: 120, truncated: true } })

describe('Cyber evidence on existing audit detail', () => {
  beforeEach(() => { vi.clearAllMocks() })
  it('reads only on demand and displays input and upstream reason separately as text', async () => {
    api.getEvidence.mockResolvedValue(fixture())
    const w = mount(CyberEvidencePanel, { props: { logId: 7 } })
    expect(api.getEvidence).not.toHaveBeenCalled()
    await w.get('button').trigger('click'); await flushPromises()
    expect(api.getEvidence).toHaveBeenCalledWith(7)
    const blocks = w.findAll('pre')
    expect(blocks[0].text()).toContain('SYNTHETIC INPUT')
    expect(blocks[0].text()).not.toContain('SYNTHETIC UPSTREAM ERROR')
    expect(blocks[1].text()).toBe('SYNTHETIC UPSTREAM ERROR')
    expect(w.text()).toContain('admin.riskControl.evidence.truncated')
    expect(w.text()).toContain('UID 42')
  })
  it('shows missing history without reconstructing input, and clears content on row changes', async () => {
    api.getEvidence.mockResolvedValue({ ...fixture(), status: 'historical_unavailable', payload: undefined })
    const w = mount(CyberEvidencePanel, { props: { logId: 7 } })
    await w.get('button').trigger('click'); await flushPromises()
    expect(w.text()).toContain('admin.riskControl.evidence.noHistory')
    expect(w.findAll('pre')).toHaveLength(0)
    await w.setProps({ logId: 8 })
    expect(w.text()).not.toContain('UID 42')
  })
  it('deletes retained content and does not expose backend errors', async () => {
    api.getEvidence.mockResolvedValue(fixture()); api.deleteEvidence.mockResolvedValue(undefined)
    const w = mount(CyberEvidencePanel, { props: { logId: 7 } })
    await w.get('button').trigger('click'); await flushPromises()
    await w.findAll('button').at(-1)!.trigger('click'); await flushPromises()
    expect(api.deleteEvidence).toHaveBeenCalledWith(7)
    expect(w.findAll('pre')).toHaveLength(0)
    api.getEvidence.mockRejectedValue(new Error('SENSITIVE ERROR'))
    await w.get('button').trigger('click'); await flushPromises()
    expect(w.text()).not.toContain('SENSITIVE ERROR')
    expect(w.text()).toContain('admin.riskControl.evidence.failed')
  })
  it('configures bounded retention separately and exposes key and failure state', async () => {
    api.getEvidenceConfig.mockResolvedValue({ config: { enabled: true, retention_days: 7 }, runtime: { encryption_ready: false, saved: 1, failed: 2, dropped: 3, queue_depth: 0, queue_capacity: 64 } })
    const w = mount(CyberEvidenceSettings)
    await w.get('button').trigger('click'); await flushPromises()
    expect(w.text()).toContain('admin.riskControl.evidence.keyMissing')
    await w.get('input[type="number"]').setValue(31)
    expect(w.findAll('button').at(-1)!.attributes('disabled')).toBeDefined()
    await w.get('input[type="number"]').setValue(3)
    api.updateEvidenceConfig.mockResolvedValue({ enabled: true, retention_days: 3 })
    await w.findAll('button').at(-1)!.trigger('click'); await flushPromises()
    expect(api.updateEvidenceConfig).toHaveBeenCalledWith({ enabled: true, retention_days: 3, parse_limit_mib: 16, body_limit_mib: 32 })
  })

  it('shows omission details and upstream reason even when input cannot be extracted', async () => {
    api.getEvidence.mockResolvedValue({ ...fixture(), payload: { ...fixture().payload, input: '', omission: 'request_exceeds_parse_limit', scanned_bytes: 1048576, stored_bytes: 0, messages_retained: 0, messages_omitted: 0, complete: false } })
    const w = mount(CyberEvidencePanel, { props: { logId: 7 } })
    await w.get('button').trigger('click'); await flushPromises()
    expect(w.get('[data-testid="evidence-coverage"]').exists()).toBe(true)
    expect(w.text()).toContain('admin.riskControl.evidence.metadataOnly')
    expect(w.text()).toContain('admin.riskControl.evidence.status.request_exceeds_parse_limit')
    expect(w.findAll('pre')).toHaveLength(1)
    expect(w.get('pre').text()).toBe('SYNTHETIC UPSTREAM ERROR')
  })

  it('keeps retained-body export separate from a truncated preview', async () => {
    api.getEvidence.mockResolvedValue({ ...fixture(), payload: { ...fixture().payload, body_retention_version: 1, request_body_bytes: 2000000, response_bytes: 12000 } })
    const w = mount(CyberEvidencePanel, { props: { logId: 7, autoLoad: true } })
    await flushPromises()
    expect(w.get('[data-testid="evidence-retained-body"]').text()).toContain('admin.riskControl.evidence.retainedRequest')
    expect(w.text()).toContain('admin.riskControl.evidence.truncated')
    expect(w.findAll('button').some(b => b.text() === 'admin.riskControl.evidence.exportRetained')).toBe(true)
    w.unmount()
  })

  it('does not label historical snapshots as retained full request bodies', async () => {
    api.getEvidence.mockResolvedValue({ ...fixture(), payload: { ...fixture().payload, request_body_bytes: 0, response_bytes: 0 } })
    const w = mount(CyberEvidencePanel, { props: { logId: 7, autoLoad: true } })
    await flushPromises()
    expect(w.find('[data-testid="evidence-retained-body"]').exists()).toBe(false)
    expect(w.findAll('button').some(b => b.text() === 'admin.riskControl.evidence.export')).toBe(true)
    w.unmount()
  })

  it('rejects an out-of-range parse limit before saving', async () => {
    api.getEvidenceConfig.mockResolvedValue({ config: { enabled: true, retention_days: 7, parse_limit_mib: 16 }, runtime: {} })
    const w = mount(CyberEvidenceSettings)
    await w.get('button').trigger('click'); await flushPromises()
    await w.get('[data-testid="evidence-parse-limit"]').setValue(65)
    expect(w.findAll('button').at(-1)!.attributes('disabled')).toBeDefined()
    expect(api.updateEvidenceConfig).not.toHaveBeenCalled()
    await w.get('[data-testid="evidence-parse-limit"]').setValue(16)
    await w.get('[data-testid="evidence-body-limit"]').setValue(65)
    expect(w.findAll('button').at(-1)!.attributes('disabled')).toBeDefined()
  })

  it('loads when explicitly opened and ignores a late response from a previous row', async () => {
    let resolveOld!: (value: unknown) => void
    api.getEvidence.mockReturnValueOnce(new Promise(resolve => { resolveOld = resolve }))
    const w = mount(CyberEvidencePanel, { props: { logId: 7, autoLoad: true } })
    expect(api.getEvidence).toHaveBeenCalledWith(7)
    expect(w.text()).toContain('common.loading')
    api.getEvidence.mockResolvedValueOnce({ ...fixture(), log_id: 8, request_id: 'req_current' })
    await w.setProps({ logId: 8 }); await flushPromises()
    expect(w.text()).toContain('req_current')
    resolveOld({ ...fixture(), request_id: 'req_stale' }); await flushPromises()
    expect(w.text()).not.toContain('req_stale')
    expect(w.text()).toContain('req_current')
    expect(w.findAll('button').some(b => b.text() === 'admin.riskControl.evidence.load')).toBe(false)
    w.unmount()
  })

  it('retains the audit reason for historical rows without duplicating input placeholders', async () => {
    api.getEvidence.mockResolvedValue({ ...fixture(), status: 'request_exceeds_parse_limit', payload: undefined })
    const w = mount(CyberEvidencePanel, { props: { logId: 7, autoLoad: true, fallbackReason: 'HISTORICAL REJECTION' } })
    await flushPromises()
    expect(w.get('pre').text()).toBe('HISTORICAL REJECTION')
    expect(w.text()).not.toContain('admin.riskControl.evidence.noInputSummary')
    w.unmount()
  })
})
